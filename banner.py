"""启动横幅：给 .bat 启动器打印中文提示。

为什么要单独一个文件：cmd 按系统代码页(GBK)读取 .bat，里面直接写 UTF-8 中文会乱码
并截断命令行。所以把中文全部交给 Python 打印（配合 chcp 65001 + PYTHONUTF8=1）。
"""
import sys

DEMO = "demo" in sys.argv

BANNER = """
================================================================
                吃饱饱助手 · 智能体终端演示
        真实本地大模型 + 真实工具调用（不是网页版）
================================================================
"""

DEMO_HELP = """
即将自动演示一整段对话，你不需要输入任何内容，大约 1~3 分钟。

屏幕上会看到：
  [工具] 调用 xxx(...)   ← 模型自己决定调用哪个工具、传什么参数
  ↳ {...}                ← 工具真实返回的数据
  🎡 转盘概率             ← 真实计算，拒绝后会重排
"""

INTER_HELP = """
直接打字跟智能体聊天，它会真实调用工具。可以这样说：

  我在金海校区，想吃火锅，预算30以内      → 有想法，直接给方案
  随便   /   不知道吃啥                    → 没想法，弹出大转盘

转盘里可以：
  输数字    选中那一项
  r         按权重随机转一下
  -菜名     拒绝这项（权重清零，概率重排）

  输入 exit 退出
"""

if __name__ == "__main__":
    sys.stdout.write(BANNER)
    sys.stdout.write(DEMO_HELP if DEMO else INTER_HELP)
    sys.stdout.flush()
